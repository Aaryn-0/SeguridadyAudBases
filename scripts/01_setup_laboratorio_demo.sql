-- =============================================================================
-- 1. CONTROL A.5.17 / A.8.5: PERFIL DE AUTENTICACIÓN SEGURA Y CONTRASEÑAS
-- =============================================================================
PROMPT [1/6] Creando perfil de seguridad PRF_ISO27001_CONFIDENCIAL...

BEGIN
    EXECUTE IMMEDIATE 'CREATE PROFILE PRF_ISO27001_CONFIDENCIAL LIMIT
        FAILED_LOGIN_ATTEMPTS 3
        PASSWORD_LIFE_TIME 60
        PASSWORD_REUSE_TIME 365
        PASSWORD_REUSE_MAX 10
        PASSWORD_LOCK_TIME 1/24
        PASSWORD_GRACE_TIME 5
        INACTIVE_ACCOUNT_TIME 30
        SESSIONS_PER_USER 3
        IDLE_TIME 15';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -2379 THEN
            DBMS_OUTPUT.PUT_LINE('El perfil PRF_ISO27001_CONFIDENCIAL ya existe.');
        ELSE
            RAISE;
        END IF;
END;
/

-- =============================================================================
-- 2. CONTROL A.5.15 / A.5.16 / A.5.18 / A.8.2: SEPARACIÓN DE FUNCIONES Y ROLES
-- =============================================================================
PROMPT [2/6] Creando roles bajo el Principio de Mínimo Privilegio...

BEGIN
    FOR r IN (
        SELECT 'ROL_APP_LECTURA_PII' AS rol FROM DUAL UNION ALL
        SELECT 'ROL_ANALISTA_ANONIMO' FROM DUAL UNION ALL
        SELECT 'ROL_AUDITOR_ISO27001' FROM DUAL
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'CREATE ROLE ' || r.rol;
        EXCEPTION
            WHEN OTHERS THEN NULL;
        END;
    END LOOP;
END;
/

-- Creación de usuario propietario del esquema de datos sensibles (Ley N.° 8968)
BEGIN
    EXECUTE IMMEDIATE 'CREATE USER USR_CUSTODIO_DATOS IDENTIFIED BY "Cust0d1o#UNA2026!"
        PROFILE PRF_ISO27001_CONFIDENCIAL
        DEFAULT TABLESPACE USERS
        QUOTA 50M ON USERS
        ACCOUNT UNLOCK';
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE TO USR_CUSTODIO_DATOS';
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Nota: Usuario USR_CUSTODIO_DATOS ya existe o requiere ajuste.');
END;
/

-- Creación de usuario analista (sin acceso a PII en claro)
BEGIN
    EXECUTE IMMEDIATE 'CREATE USER USR_ANALISTA_BI IDENTIFIED BY "An4l1st4#UNA2026!"
        PROFILE PRF_ISO27001_CONFIDENCIAL
        DEFAULT TABLESPACE USERS
        ACCOUNT UNLOCK';
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, ROL_ANALISTA_ANONIMO TO USR_ANALISTA_BI';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- Creación de usuario auditor externo/interno (Separación de funciones respecto al DBA)
BEGIN
    EXECUTE IMMEDIATE 'CREATE USER USR_AUDITOR_EXT IDENTIFIED BY "Aud1t0r#UNA2026!"
        PROFILE PRF_ISO27001_CONFIDENCIAL
        DEFAULT TABLESPACE USERS
        ACCOUNT UNLOCK';
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, AUDIT_VIEWER, SELECT_CATALOG_ROLE TO USR_AUDITOR_EXT';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- =============================================================================
-- 3. CONTROL A.5.12: TABLA CON DATOS SENSIBLES Y ACCESO RESTRINGIDO (LEY 8968)
-- =============================================================================
PROMPT [3/6] Creando tabla de expedientes con clasificación de datos (Ley 8968 CR)...

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL (
        ID_PACIENTE          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CEDULA_IDENTIDAD     VARCHAR2(20)  NOT NULL, -- Acceso Restringido (Ley 8968)
        NOMBRE_COMPLETO      VARCHAR2(120) NOT NULL,
        CORREO_ELECTRONICO   VARCHAR2(100),
        TELEFONO             VARCHAR2(20),
        DIAGNOSTICO_CLINICO  VARCHAR2(250) NOT NULL, -- Dato Sensible (Art. 3 Ley 8968)
        SALARIO_MENSUAL_CRC  NUMBER(12,2),           -- Acceso Restringido
        DEPARTAMENTO_CLINICA VARCHAR2(50)  NOT NULL,
        FECHA_REGISTRO       TIMESTAMP DEFAULT SYSTIMESTAMP
    )';
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Tabla PACIENTES_CONFIDENCIAL ya existe.');
END;
/

-- Comentarios de clasificación de activos en el diccionario de datos (Control A.5.12)
COMMENT ON TABLE USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL IS
    '[CLASIFICACION: CONFIDENCIAL / DATOS SENSIBLES LEY 8968 CR] Activo crítico con PII y datos médicos.';
COMMENT ON COLUMN USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL.CEDULA_IDENTIDAD IS
    '[CLASIFICACION: RESTRINGIDO] Identificador nacional sujeto a enmascaramiento A.8.11';
COMMENT ON COLUMN USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL.DIAGNOSTICO_CLINICO IS
    '[CLASIFICACION: CONFIDENCIAL-SENSIBLE] Dato médico protegido bajo Art. 3 y 9 Ley 8968';
COMMENT ON COLUMN USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL.SALARIO_MENSUAL_CRC IS
    '[CLASIFICACION: CONFIDENCIAL] Dato socioeconómico restringido';

-- Otorgar lectura controlada al rol de analista (que será filtrado por VPD y Data Redaction)
GRANT SELECT ON USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL TO ROL_ANALISTA_ANONIMO;

-- =============================================================================
-- 4. CONTROL A.8.11: ENMASCARAMIENTO DINÁMICO (ORACLE DATA REDACTION - DBMS_REDACT)
--    (En ediciones Enterprise; en XE se incluye también vista de enmascaramiento alternativo)
-- =============================================================================
PROMPT [4/6] Configurando Enmascaramiento de Datos (Control A.8.11)...

BEGIN
    DBMS_REDACT.ADD_POLICY(
        object_schema       => 'USR_CUSTODIO_DATOS',
        object_name         => 'PACIENTES_CONFIDENCIAL',
        column_name         => 'CEDULA_IDENTIDAD',
        policy_name         => 'POL_REDACT_PII_PACIENTES',
        function_type       => DBMS_REDACT.PARTIAL,
        function_parameters => 'VVVVFVVVVFVVVV,VVVV-VVVV-VVVV,*,1,7',
        expression          => 'SYS_CONTEXT(''USERENV'',''SESSION_USER'') != ''USR_CUSTODIO_DATOS'''
    );

    DBMS_REDACT.ALTER_POLICY(
        object_schema       => 'USR_CUSTODIO_DATOS',
        object_name         => 'PACIENTES_CONFIDENCIAL',
        column_name         => 'SALARIO_MENSUAL_CRC',
        policy_name         => 'POL_REDACT_PII_PACIENTES',
        action              => DBMS_REDACT.ADD_COLUMN,
        function_type       => DBMS_REDACT.FULL
    );
    DBMS_OUTPUT.PUT_LINE('Política DBMS_REDACT aplicada exitosamente.');
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Aviso: DBMS_REDACT requiere licencia Advanced Security o privilegio específico. Se crea vista enmascarada de respaldo para XE.');
END;
/

-- Vista de enmascaramiento nativo compatible con cualquier edición (incluyendo XE sin ASO)
CREATE OR REPLACE VIEW USR_CUSTODIO_DATOS.VW_PACIENTES_ENMASCARADOS AS
SELECT
    ID_PACIENTE,
    CASE
        WHEN SYS_CONTEXT('USERENV', 'SESSION_USER') IN ('USR_CUSTODIO_DATOS') THEN CEDULA_IDENTIDAD
        ELSE '***-****-' || SUBSTR(CEDULA_IDENTIDAD, -4)
    END AS CEDULA_IDENTIDAD,
    SUBSTR(NOMBRE_COMPLETO, 1, 1) || '*****' AS NOMBRE_ANONIMIZADO,
    REGEXP_REPLACE(CORREO_ELECTRONICO, '(^.).*(@.*$)', '\1***\2') AS CORREO_ENMASCARADO,
    CASE
        WHEN SYS_CONTEXT('USERENV', 'SESSION_USER') IN ('USR_CUSTODIO_DATOS') THEN DIAGNOSTICO_CLINICO
        ELSE '[DATO SENSIBLE PROTEGIDO - LEY 8968]'
    END AS DIAGNOSTICO_CLINICO,
    DEPARTAMENTO_CLINICA,
    FECHA_REGISTRO
FROM USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL;

GRANT SELECT ON USR_CUSTODIO_DATOS.VW_PACIENTES_ENMASCARADOS TO ROL_ANALISTA_ANONIMO;

-- =============================================================================
-- 5. CONTROL A.8.3: RESTRICCIÓN DE ACCESO POR FILAS (VPD / DBMS_RLS)
-- =============================================================================
PROMPT [5/6] Configurando Virtual Private Database (Row-Level Security - Control A.8.3)...

CREATE OR REPLACE FUNCTION USR_CUSTODIO_DATOS.FN_VPD_FILTRO_CONFIDENCIAL (
    p_schema IN VARCHAR2,
    p_object IN VARCHAR2
) RETURN VARCHAR2 AS
    v_user VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
BEGIN
    -- El custodio ve todos los registros; otros usuarios solo ven registros públicos/estadísticos
    IF v_user IN ('SYS', 'USR_CUSTODIO_DATOS') THEN
        RETURN '1=1';
    ELSIF v_user = 'USR_ANALISTA_BI' THEN
        RETURN 'DEPARTAMENTO_CLINICA = ''EPIDEMIOLOGIA_PUBLICA''';
    ELSE
        -- Zero Trust: denegar por defecto acceso a filas si no tiene contexto explícito
        RETURN '1=0';
    END IF;
END;
/

BEGIN
    DBMS_RLS.ADD_POLICY(
        object_schema   => 'USR_CUSTODIO_DATOS',
        object_name     => 'PACIENTES_CONFIDENCIAL',
        policy_name     => 'POL_VPD_AISLAMIENTO_FILAS',
        function_schema => 'USR_CUSTODIO_DATOS',
        policy_function => 'FN_VPD_FILTRO_CONFIDENCIAL',
        statement_types => 'SELECT, UPDATE, DELETE',
        update_check    => TRUE,
        enable          => TRUE
    );
    DBMS_OUTPUT.PUT_LINE('Política VPD (DBMS_RLS) activada correctamente.');
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Aviso VPD: ' || SQLERRM);
END;
/

-- =============================================================================
-- 6. CONTROL A.5.33 / A.8.15: POLÍTICA DE AUDITORÍA UNIFICADA (UNIFIED AUDITING)
-- =============================================================================
PROMPT [6/6] Creando y habilitando Políticas de Auditoría Unificada (Controles A.5.33 y A.8.15)...

BEGIN
    EXECUTE IMMEDIATE 'CREATE AUDIT POLICY POL_AUD_CONFIDENCIALIDAD_ISO27001
        ACTIONS
            SELECT, INSERT, UPDATE, DELETE ON USR_CUSTODIO_DATOS.PACIENTES_CONFIDENCIAL,
            CREATE USER, ALTER USER, DROP USER,
            GRANT, REVOKE,
            ALTER SYSTEM, ALTER DATABASE';
    EXECUTE IMMEDIATE 'AUDIT POLICY POL_AUD_CONFIDENCIALIDAD_ISO27001';
    EXECUTE IMMEDIATE 'AUDIT POLICY POL_AUD_CONFIDENCIALIDAD_ISO27001 WHENEVER NOT SUCCESSFUL';
    DBMS_OUTPUT.PUT_LINE('Política de Auditoría Unificada POL_AUD_CONFIDENCIALIDAD_ISO27001 activa.');
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Aviso Auditoría: ' || SQLERRM);
END;
/

